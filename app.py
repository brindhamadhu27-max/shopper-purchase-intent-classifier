"""Streamlit interface for evaluating the five saved classifiers."""
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report,
    ConfusionMatrixDisplay
)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
TARGET = "Revenue"

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}

st.set_page_config(page_title="Purchase Intention Classifier", page_icon="🛍️", layout="wide")
st.title("Online Shopper Purchase Intention")
st.write(
    "Upload a labelled test CSV to evaluate one of the five previously trained "
    "classifiers. The app loads saved pipelines and does not retrain on uploaded data."
)

with st.sidebar:
    st.header("Evaluation settings")
    selected_model = st.selectbox("Choose a classifier", list(MODEL_FILES))
    st.caption("The uploaded CSV must contain the 17 input features and the Revenue target.")

uploaded = st.file_uploader("Upload test data (CSV)", type=["csv"])

if uploaded is None:
    st.info("Upload the test_data.csv file generated by train_models.py to begin.")
    st.stop()

try:
    test_df = pd.read_csv(uploaded)
except Exception as exc:
    st.error(f"Could not read this CSV: {exc}")
    st.stop()

if TARGET not in test_df.columns:
    st.error(f"Required target column '{TARGET}' is missing from the uploaded CSV.")
    st.stop()

target_values = test_df[TARGET]
if target_values.isna().any():
    st.error("The target column contains missing values. Please upload a labelled test CSV.")
    st.stop()

X_test = test_df.drop(columns=[TARGET])
y_test = target_values.astype(bool)

model_path = MODEL_DIR / MODEL_FILES[selected_model]
if not model_path.exists():
    st.error(f"Saved model not found: {model_path.name}. Run train_models.py first.")
    st.stop()

try:
    model = joblib.load(model_path)
    expected_features = list(model.feature_names_in_)
    missing = [c for c in expected_features if c not in X_test.columns]
    extra = [c for c in X_test.columns if c not in expected_features]
    if missing:
        st.error("Missing required input columns: " + ", ".join(missing))
        st.stop()
    if extra:
        st.warning("Extra columns will be ignored: " + ", ".join(extra))
    X_test = X_test[expected_features]

    predictions = model.predict(X_test)
    probabilities = model.predict_proba(X_test)
    positive_index = list(model.classes_).index(True)
    positive_probabilities = probabilities[:, positive_index]

    metrics = {
        "Accuracy": accuracy_score(y_test, predictions),
        "AUC": roc_auc_score(y_test, positive_probabilities),
        "Precision": precision_score(y_test, predictions, zero_division=0),
        "Recall": recall_score(y_test, predictions, zero_division=0),
        "F1 Score": f1_score(y_test, predictions, zero_division=0),
        "MCC": matthews_corrcoef(y_test, predictions)
    }

    st.subheader(f"Results: {selected_model}")
    cols = st.columns(3)
    for i, (metric_name, metric_value) in enumerate(metrics.items()):
        cols[i % 3].metric(metric_name, f"{metric_value:.4f}")

    left, right = st.columns(2)
    with left:
        st.subheader("Confusion matrix")
        cm = confusion_matrix(y_test, predictions, labels=[False, True])
        fig, ax = plt.subplots()
        ConfusionMatrixDisplay(
            confusion_matrix=cm, display_labels=["No purchase", "Purchase"]
        ).plot(ax=ax, colorbar=False)
        st.pyplot(fig)
        plt.close(fig)

    with right:
        st.subheader("Classification report")
        report = classification_report(
            y_test, predictions,
            labels=[False, True],
            target_names=["No purchase", "Purchase"],
            output_dict=True,
            zero_division=0
        )
        st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

    st.caption(f"Evaluated {len(test_df)} labelled rows. No model training was performed in this app.")
except Exception as exc:
    st.error(f"Evaluation failed: {exc}")
